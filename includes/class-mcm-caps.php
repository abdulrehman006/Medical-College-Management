<?php
/**
 * Capabilities for the student records.
 *
 * Students are the only personal data the plugin stores, so they get their own
 * capability set rather than sharing the generic post capabilities. Without
 * this, anyone who can write a blog post (Author, Contributor) could open the
 * student roll and read PMDC numbers, emails, phone numbers, dates of birth,
 * addresses and guardian contacts.
 *
 * Grants are applied on activation and on every version upgrade, so an existing
 * site picks them up without the admin doing anything.
 *
 * @package MedicalCollegeManager
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

class MCM_Caps {

	/**
	 * Roles that may manage student records.
	 *
	 * Filter this to hand access to a Registrar or Admissions Officer role:
	 *
	 *   add_filter( 'mcm_student_roles', function ( $roles ) {
	 *       $roles[] = 'registrar';
	 *       return $roles;
	 *   } );
	 *
	 * @return string[]
	 */
	public static function student_roles() {
		return (array) apply_filters( 'mcm_student_roles', array( 'administrator' ) );
	}

	/**
	 * Every capability generated by the student capability_type.
	 *
	 * @return string[]
	 */
	public static function student_caps() {
		return array(
			'edit_mcm_student',
			'read_mcm_student',
			'delete_mcm_student',
			'edit_mcm_students',
			'edit_others_mcm_students',
			'publish_mcm_students',
			'read_private_mcm_students',
			'delete_mcm_students',
			'delete_private_mcm_students',
			'delete_published_mcm_students',
			'delete_others_mcm_students',
			'edit_private_mcm_students',
			'edit_published_mcm_students',
			'create_mcm_students',
		);
	}

	/**
	 * Give the student capabilities to the configured roles.
	 *
	 * Idempotent: safe to run on every activation and upgrade. Roles that are
	 * no longer configured have the capabilities taken back, so removing a role
	 * from the filter actually revokes access rather than leaving it behind.
	 */
	public static function grant() {
		$allowed = self::student_roles();
		$caps    = self::student_caps();

		foreach ( wp_roles()->get_names() as $role_key => $label ) {
			$role = get_role( $role_key );
			if ( ! $role ) {
				continue;
			}
			$should_have = in_array( $role_key, $allowed, true );

			foreach ( $caps as $cap ) {
				$has = $role->has_cap( $cap );
				if ( $should_have && ! $has ) {
					$role->add_cap( $cap );
				} elseif ( ! $should_have && $has ) {
					$role->remove_cap( $cap );
				}
			}
		}
	}

	/**
	 * Strip every student capability from every role. Called on uninstall so a
	 * deleted plugin does not leave orphan capabilities behind.
	 */
	public static function revoke_all() {
		$caps = self::student_caps();
		foreach ( wp_roles()->get_names() as $role_key => $label ) {
			$role = get_role( $role_key );
			if ( ! $role ) {
				continue;
			}
			foreach ( $caps as $cap ) {
				$role->remove_cap( $cap );
			}
		}
	}
}
